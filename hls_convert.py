import os
import hls4ml
import glob
import re
import xml.etree.ElementTree as ET
import subprocess

def hls_convert(model, full_name, input_shape=(256, 15), precision='fixed<16,6>'):
    print(f" [HLS] Converting model: {full_name} with precision {precision}")
    
    config = hls4ml.utils.config_from_pytorch_model(
        model,
        input_shape=input_shape,
        granularity='name',
        default_precision=precision,
        default_reuse_factor=5
    )

    config['Model']['Strategy'] = 'Resource'
    config['Model']['IOType'] = 'io_stream'

    # print("Capas detectadas:", list(config['LayerName'].keys()))

    if 'LayerName' in config:
        for layer_name, layer_cfg in config['LayerName'].items():
            layer_cfg['Strategy'] = 'Resource'
            layer_cfg['ReuseFactor'] = 5

    # 3. C++ project generation
    output_dir = os.path.join('hls', full_name)
    hls_model = hls4ml.converters.convert_from_pytorch_model(
        model,
        input_shape=input_shape,
        hls_config=config,
        output_dir=output_dir,
        part='xc7z020clg400-1',
        backend='Vitis'
    )

    hls_model.compile()

    # 5. Build the project with Vivado
    try:
        hls_model.build(csim=True, synth=True, export=True)
    except Exception as err:
        cycles, latency_us = extract_latency(project_path=output_dir)
        print(f" [HLS] Latency extracted: {latency_us:.4f} us, Cycles: {cycles}")
        
        export_zip = os.path.join(output_dir, 'myproject_prj/solution1/impl/export.zip')
        csynth_rpt = os.path.join(output_dir, 'myproject_prj/solution1/syn/report/csynth.rpt')

        if cycles is not None or latency_us > 0 or os.path.exists(export_zip) or os.path.exists(csynth_rpt):
            print("\n" + "!"*80)
            print(" [HLS Warning] Vitis HLS completed the C-Synthesis and the IP export with success.")
            print("               The memory crash on tool closing was ignored.")
            print("               Continuing the framework execution...")
            print("!"*80 + "\n")
        else:
            log_file = os.path.join(output_dir, 'vitis_hls.log')
            if os.path.exists(log_file):
                print("\n" + "="*25 + " LAST LINES OF VITIS_HLS.LOG " + "="*25)
                with open(log_file, 'r') as f:
                    lines = f.readlines()
                    for line in lines[-30:]:
                        print(line.strip())
                print("="*80 + "\n")
            raise err

    return hls_model


def extract_latency(project_path):
    """
    Extracts the latency by first reading the structured csynth.xml file (100% reliable in Vitis 2026).
    If it does not exist, it uses a generic fallback on any csynth.rpt.
    """
    if not os.path.exists(project_path):
        return None, 0.0

    # Attempt to extract latency from csynth.xml or csynth.rpt files
    xml_files = glob.glob(os.path.join(project_path, '**', 'csynth.xml'), recursive=True)
    if xml_files:
        try:
            tree = ET.parse(xml_files[0])
            root = tree.getroot()
            worst_lat = root.find('.//PerformanceEstimates/SummaryOfOverallLatency/Worst-caseLatency')
            if worst_lat is not None and worst_lat.text.strip().isdigit():
                cycles = int(worst_lat.text.strip())
                return cycles, (cycles * 5.0) / 1000.0
        except Exception:
            pass

    # 2. Fallback: Extract latency from csynth.rpt files
    rpt_files = glob.glob(os.path.join(project_path, '**', '*csynth.rpt'), recursive=True)
    for rpt_path in rpt_files:
        try:
            with open(rpt_path, 'r') as f:
                lines = f.readlines()
            
            in_summary = False
            for line in lines:
                if '* Summary:' in line:
                    in_summary = True
                    continue
                if in_summary and '|' in line and not any(k in line for k in ['Latency', '---', 'min', 'max', 'Module']):
                    parts = [p.strip() for p in line.split('|') if p.strip()]
                    if len(parts) >= 2:
                        for p in parts[:2]:
                            if p.isdigit():
                                cycles = int(p)
                                return cycles, (cycles * 5.0) / 1000.0
        except Exception:
            pass

    return None, 0.0


def run_vivado_power_analysis(output_dir):
    """
    Synthetizes in memory (In-Memory) the Verilog RTL generated by Vitis HLS 
    and runs report_power using the RuntimeOptimized directive
    """
    verilog_dir = os.path.join(output_dir, 'myproject_prj/solution1/impl/ip/hdl/verilog')
    if not os.path.exists(verilog_dir):
        verilog_dir = os.path.join(output_dir, 'myproject_prj/solution1/impl/verilog')

    if not os.path.exists(verilog_dir):
        print(f" [Warning] Could not find Verilog files in: {verilog_dir}")
        return

    tcl_script_path = os.path.join(output_dir, 'run_power_analysis.tcl')
    power_rpt_path = os.path.join(output_dir, 'power_report.rpt')
    power_xml_path = os.path.join(output_dir, 'power_report.xml')

    tcl_content = f"""
    create_project -in_memory -part xc7z020clg400-1
    
    foreach f [glob -nocomplain {verilog_dir}/*.v] {{
        if {{![string match "*_tb.v" $f]}} {{
            read_verilog $f
        }}
    }}
    
    synth_design -top myproject -part xc7z020clg400-1 -mode out_of_context -directive RuntimeOptimized
    
    create_clock -period 5.000 -name ap_clk [get_ports ap_clk]
    report_power -file {power_rpt_path}
    report_power -file {power_xml_path} -format xml
    exit
    """
    
    with open(tcl_script_path, 'w') as f:
        f.write(tcl_content)

    print(" [Vivado] Executing quick power analysis of RTL in memory...")
    log_path = os.path.join(output_dir, 'vivado_power.log')
    with open(log_path, 'w') as log_file:
        subprocess.run(
            f"vivado -mode batch -source {tcl_script_path}", 
            shell=True, 
            stdout=log_file, 
            stderr=log_file
        )


def extract_energy_joules(project_path, latency_us):
    """
    Extracts the dynamic power (W) from the Vivado report and calculates the energy (J) by inference
    """
    if latency_us is None or latency_us <= 0:
        return 0.0, 0.0

    p_dynamic_w = 0.0

    # 1. Strategy A: Read directly from the text report power_report.rpt
    rpt_files = glob.glob(os.path.join(project_path, '**', 'power_report.rpt'), recursive=True)
    if not rpt_files and os.path.exists(os.path.join(project_path, 'power_report.rpt')):
        rpt_files = [os.path.join(project_path, 'power_report.rpt')]

    if rpt_files:
        try:
            with open(rpt_files[0], 'r') as f:
                content = f.read()
            # Corrected regex: looks for the row "| Dynamic (W) | <value> |"
            patterns = [
                r'\|\s*Dynamic\s*\(W\)\s*\|\s*([0-9\.\-+eE]+)\s*\|',
                r'Dynamic\s*\(W\)\s*[:|]\s*([0-9\.\-+eE]+)'
            ]
            for pat in patterns:
                match = re.search(pat, content, re.IGNORECASE)
                if match:
                    p_dynamic_w = float(match.group(1))
                    break
        except Exception as e:
            print(f" [Error RPT Parser] {e}")

    # 2. Strategy B: Read from the XML schema power_report.xml (Direct search by row)
    if p_dynamic_w == 0.0:
        xml_files = glob.glob(os.path.join(project_path, '**', 'power_report.xml'), recursive=True)
        if not xml_files and os.path.exists(os.path.join(project_path, 'power_report.xml')):
            xml_files = [os.path.join(project_path, 'power_report.xml')]
            
        if xml_files:
            try:
                tree = ET.parse(xml_files[0])
                root = tree.getroot()
                for row in root.findall('.//row'):
                    header = row.attrib.get('Header', '')
                    if 'Dynamic' in header:
                        cell = row.find('cell[@Header="Power (W)"]')
                        if cell is None:
                            cell = row.find('cell')
                        if cell is not None and cell.text:
                            p_dynamic_w = float(cell.text)
                            break
            except Exception as e:
                print(f" [Error XML Parser] {e}")

    # T_inference in seconds (us -> s)
    t_seconds = latency_us * 1e-6
    
    # E (J) = P (W) * T (s)
    energy_joules = p_dynamic_w * t_seconds

    return p_dynamic_w, energy_joules
